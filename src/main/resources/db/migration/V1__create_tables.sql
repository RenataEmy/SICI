CREATE TABLE tb_sector (
    sector_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    acronym VARCHAR(6) NOT NULL,
    CONSTRAINT uk_tb_sector_acronym UNIQUE (acronym)
);

CREATE TABLE tb_user (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(100) NOT NULL,
    registration INTEGER NOT NULL,
    type VARCHAR(255) NOT NULL,
    sector_id BIGINT,
    CONSTRAINT uk_tb_user_email UNIQUE (email),
    CONSTRAINT fk_tb_user_sector FOREIGN KEY (sector_id)
        REFERENCES tb_sector (sector_id)
);

CREATE TABLE tb_category (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(200) NOT NULL,
    sector_id BIGINT,
    CONSTRAINT fk_tb_category_sector FOREIGN KEY (sector_id)
        REFERENCES tb_sector (sector_id)
);

CREATE TABLE tb_ticket (
    ticket_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(100) NOT NULL,
    description VARCHAR(250) NOT NULL,
    location VARCHAR(50) NOT NULL,
    priority VARCHAR(255),
    status VARCHAR(255),
    open_date TIMESTAMP,
    close_date TIMESTAMP,
    solution VARCHAR(300),
    request_id BIGINT,
    category_id BIGINT,
    tech_id BIGINT,
    CONSTRAINT fk_tb_ticket_request FOREIGN KEY (request_id)
        REFERENCES tb_user (user_id),
    CONSTRAINT fk_tb_ticket_category FOREIGN KEY (category_id)
        REFERENCES tb_category (category_id),
    CONSTRAINT fk_tb_ticket_tech FOREIGN KEY (tech_id)
        REFERENCES tb_user (user_id)
);

CREATE TABLE tb_interaction (
    interaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    text VARCHAR(300) NOT NULL,
    date_time TIMESTAMP NOT NULL,
    ticket_id BIGINT,
    author_id BIGINT,
    CONSTRAINT fk_tb_interaction_ticket FOREIGN KEY (ticket_id)
        REFERENCES tb_ticket (ticket_id),
    CONSTRAINT fk_tb_interaction_author FOREIGN KEY (author_id)
        REFERENCES tb_user (user_id)
);

CREATE INDEX idx_tb_user_sector_id ON tb_user (sector_id);
CREATE INDEX idx_tb_category_sector_id ON tb_category (sector_id);
CREATE INDEX idx_tb_ticket_request_id ON tb_ticket (request_id);
CREATE INDEX idx_tb_ticket_category_id ON tb_ticket (category_id);
CREATE INDEX idx_tb_ticket_tech_id ON tb_ticket (tech_id);
CREATE INDEX idx_tb_interaction_ticket_id ON tb_interaction (ticket_id);
CREATE INDEX idx_tb_interaction_author_id ON tb_interaction (author_id);
